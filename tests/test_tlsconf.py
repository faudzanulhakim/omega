"""Hermetic tests for omega.scanning.tlsconf.

Uses a real loopback TLS server (python ssl stdlib with a self-signed
certificate generated by the host openssl binary; the whole module is
skipped gracefully when openssl or TLS support is unavailable), plus
a plain-HTTP server and a dead target.
"""

import shutil
import ssl
import subprocess
import threading
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

import pytest

from omega.scanning.deepchecks import default_fetch
from omega.scanning.tlsconf import _parse_expiry_days, run_tlsconf

openssl = shutil.which("openssl")
pytestmark = pytest.mark.skipif(openssl is None,
                                reason="openssl binary unavailable")


def _gen_cert(tmp_path, days=365, cn="127.0.0.1"):
    import os
    key = os.path.join(str(tmp_path), "key.pem")
    crt = os.path.join(str(tmp_path), "crt.pem")
    subprocess.run(
        [openssl, "req", "-x509", "-newkey", "rsa:2048", "-nodes",
         "-keyout", str(key), "-out", str(crt), "-days", str(days),
         "-subj", "/CN=%s" % cn],
        capture_output=True, timeout=60, check=True)
    return str(key), str(crt)


class _TLSHandler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def log_message(self, *a):
        pass

    def do_GET(self):
        body = b"<html>tls</html>"
        self.send_response(200)
        self.send_header("Content-Type", "text/html")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)


def _serve_tls(tmp_path, days=365, cn="127.0.0.1"):
    key, crt = _gen_cert(tmp_path, days=days, cn=cn)
    srv = ThreadingHTTPServer(("127.0.0.1", 0), _TLSHandler)
    ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    ctx.load_cert_chain(crt, key)
    srv.socket = ctx.wrap_socket(srv.socket, server_side=True)
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    return srv


@pytest.fixture(scope="module")
def tls_base():
    import tempfile
    with tempfile.TemporaryDirectory() as td:
        srv = _serve_tls(td)
        yield "https://127.0.0.1:%d" % srv.server_address[1]
        srv.shutdown()
        srv.server_close()


@pytest.fixture(scope="module")
def expiring_base():
    import tempfile
    with tempfile.TemporaryDirectory() as td:
        srv = _serve_tls(td, days=5, cn="127.0.0.1")
        yield "https://127.0.0.1:%d" % srv.server_address[1]
        srv.shutdown()
        srv.server_close()


@pytest.fixture(scope="module")
def http_base():
    srv = ThreadingHTTPServer(("127.0.0.1", 0), _TLSHandler)
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    yield "http://127.0.0.1:%d" % srv.server_address[1]
    srv.shutdown()
    srv.server_close()


def test_plain_http_info_note(http_base):
    found = run_tlsconf(http_base, default_fetch)
    assert len(found) == 1
    f = found[0]
    assert f["severity"] == "info"
    assert "skipped" in f["title"].lower()
    assert f["source"] == "omega-tlsconf"


def test_self_signed_medium_candidate(tls_base):
    found = run_tlsconf(tls_base, default_fetch)
    ss = [f for f in found if "self-signed" in f["title"].lower()]
    assert ss
    assert ss[0]["severity"] == "medium"
    assert ss[0]["verification"] == "candidate"


def test_expiring_cert_medium_candidate(expiring_base):
    found = run_tlsconf(expiring_base, default_fetch)
    exp = [f for f in found if "expires" in f["title"].lower()]
    assert exp
    assert exp[0]["severity"] == "medium"
    assert "day" in exp[0]["evidence"]


def test_weak_protocol_finding_is_high_candidate(tls_base):
    """This stdlib TLS server still accepts legacy TLS 1.1; when the
    scan detects a weak protocol the finding must be a HIGH
    candidate."""
    found = run_tlsconf(tls_base, default_fetch)
    weak = [f for f in found if "weak tls protocol" in f["title"].lower()]
    if weak:
        assert weak[0]["severity"] == "high"
        assert weak[0]["verification"] == "candidate"
        assert "TLSv1.1" in weak[0]["evidence"]


def test_dead_target_silent():
    assert run_tlsconf("https://127.0.0.1:1", default_fetch) == []


def test_never_raises_on_bad_subprocess(tls_base, monkeypatch):
    """When openssl subprocess calls fail entirely, the run falls back
    to the stdlib probe path and still never raises."""
    import omega.scanning.tlsconf as mod

    def boom(*a, **kw):
        raise OSError("no openssl")
    monkeypatch.setattr(mod.subprocess, "run", boom)
    found = run_tlsconf(tls_base, default_fetch)
    assert isinstance(found, list)
    assert not [f for f in found if "self-signed" in f["title"].lower()]


def test_parse_expiry_days_unit():
    assert _parse_expiry_days("notAfter = Nov 14 12:00:00 2099 GMT\n") \
        is not None
    assert _parse_expiry_days("garbage") is None
