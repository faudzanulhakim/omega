    parts += [f"<li>{e(ln)}</li>"
              for ln in _scope_lines(target, meta, findings, L=L)]
    parts += ["</ul>", "</section>",
              '<section id="risk-methodology">',
              f"<h2>{e(L['risk_methodology'])}</h2>", "<ul>"]
    parts += [f"<li>{e(ln)}</li>" for ln in _risk_methodology_lines(L)]
    parts += ["</ul>", "</section>",
              '<section id="findings">',
              f"<h2>{e(L['findings'])}</h2>"]
    for f in findings:
        parts.append(_html_finding(f, L))
    parts += ["</section>",
              '<section id="appendix-a">',
              f"<h2>{e(L['appendix_a'])}</h2>",
              f"<table><tr><th>{e(L['th_id'])}</th>"
              f"<th>{e(L['th_severity'])}</th>"
              f"<th>{e(L['th_verification'])}</th>"
              f"<th>{e(L['th_source'])}</th>"
              f"<th>{e(L['th_location'])}</th></tr>"]
    for f in findings:
        parts.append(
            f"<tr><td>{e(f['id'])}</td><td>{e(f['severity'])}</td>"
            f"<td>{e(f['verification'] or '—')}</td>"
            f"<td>{e(f['source'] or '—')}</td>"
            f"<td>{e(f['location'] or '—')}</td></tr>")
    ran_text = ("; ".join(str(x) for x in ran) if ran
                else L["none_recorded"])
    skipped_text = ("; ".join(str(x) for x in skipped) if skipped
                    else L["none"])
    parts += ["</table>", "</section>",
              '<section id="appendix-b">',
              f"<h2>{e(L['appendix_b'])}</h2>",
              f"<p>{e(L['ran_fmt'].format(x=ran_text))}</p>",
              f"<p>{e(L['skipped_fmt'].format(x=skipped_text))}</p>",
              "</section>",
              "<footer>",
              f"<p>{e(L['end_of_report'])}</p>",
              f"<p>{e(L['disclaimer_label'])} {e(L['disclaimer'])}</p>",
              "</footer>",
              "</body>",
              "</html>"]
    return "\n".join(parts)


