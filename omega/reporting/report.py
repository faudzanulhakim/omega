def _set_mono(para, shaded=True):
    """Give every run in a paragraph the Consolas monospace style and a
    light shaded background (evidence / code block look)."""
    from docx.shared import Pt
    for run in para.runs:
        run.font.name = "Consolas"
        run.font.size = Pt(9)
    if shaded:
        pPr = para._p.get_or_add_pPr()
        shd = pPr.makeelement(
            "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"
            "shd", {})
        shd.set("{http://schemas.openxmlformats.org/wordprocessingml/2006/"
                "main}val", "clear")
        shd.set("{http://schemas.openxmlformats.org/wordprocessingml/2006/"
                "main}fill", "F2F2F2")
        pPr.append(shd)
    return para


def _docx_page_break(doc):
    from docx.enum.text import WD_BREAK
    doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)


def _render_docx(target, findings, summary, generated_at, meta=None,
                 L=None):
    """Render a .docx document via python-docx. ImportError -> ReportError."""
    L = L or _EN
    try:
        import docx  # noqa: F401  (optional dependency)
        from docx import Document
    except ImportError as exc:
        raise ReportError(
            "docx export requires python-docx "
            f"(pip install python-docx): {exc}") from exc
    s = summary
    doc = Document()

    # --- cover page ---
    doc.add_heading(L["title"], level=0)
    doc.add_paragraph(f"{L['target']}: {target}")
    doc.add_paragraph(f"{L['engagement_date']}: {generated_at}")
    doc.add_paragraph(f"{L['version']}: {REPORT_VERSION}")
    doc.add_paragraph(L["classification"])
    _docx_page_break(doc)

    # --- executive summary ---
    doc.add_heading(L["executive_summary"], level=1)
    doc.add_paragraph(_overall_risk_text(s, L))
    doc.add_paragraph(L["severity_counts_fmt"].format(
        high=s['by_severity']['HIGH'],
        medium=s['by_severity']['MEDIUM'],
        low=s['by_severity']['LOW'],
        info=s['by_severity']['INFO'],
        confirmed=s['by_verification']['confirmed'],
        candidate=s['by_verification']['candidate'],
        corroborated=s['corroborated']))
    for o in _key_observations(findings, s, L=L):
        doc.add_paragraph(o, style="List Bullet")

    # --- scope & methodology ---
    doc.add_heading(L["scope_methodology"], level=1)
    for ln in _scope_lines(target, meta, findings, L=L):
        doc.add_paragraph(ln, style="List Bullet")

    # --- risk rating methodology ---
    doc.add_heading(L["risk_methodology"], level=1)
    table = doc.add_table(rows=1, cols=2)
    hdr = table.rows[0].cells
    hdr[0].text = L["th_severity"]
    hdr[1].text = L["th_definition"]
    for sev, definition in _SEVERITY_DEFS:
        row = table.add_row().cells
        row[0].text = sev
        row[1].text = definition
    doc.add_paragraph(L["verif_semantics_short"])

    # --- findings ---
    _docx_page_break(doc)
    doc.add_heading(L["findings"], level=1)
    for f in findings:
        doc.add_heading(f"{f['id']} [{f['severity']}] {f['title']}",
                        level=3)
        status = _verification_status(f, L)
        if status:
            doc.add_paragraph(f"{L['verification_status']}: {status}")
        if f.get("corroborated"):
            doc.add_paragraph(_corroborated_note(f, L))
        if f.get("cwe") or f.get("cvss"):
            bits = []
            if f.get("cwe"):
                bits.append(f"CWE: {f['cwe']}")
            if f.get("cvss"):
                bits.append(f"CVSS: {f['cvss']}")
            doc.add_paragraph(" | ".join(bits))
        doc.add_paragraph(f"{L['description']}: {f['description']}")
        doc.add_paragraph(f"{L['impact']}: {f['impact']}")
        doc.add_paragraph(f"{L['evidence']}:")
        ev = f["evidence"] if f["evidence"] else L["no_evidence"]
        _set_mono(doc.add_paragraph(ev))
        doc.add_paragraph(f"{L['affected_location']}: "
                          f"{f['location'] or '—'}")
        if f["manual_check"]:
            doc.add_paragraph(f"{L['manual_verification_steps']}:")
            _set_mono(doc.add_paragraph(f["manual_check"]))
        doc.add_paragraph(f"{L['recommendation']}: {f['recommendation']}")
        if f.get("references"):
            doc.add_paragraph(f"{L['references']}: "
                              + "; ".join(f["references"]))

    # --- appendix A ---
    _docx_page_break(doc)
    doc.add_heading(L["appendix_a"], level=1)
    atable = doc.add_table(rows=1, cols=5)
    hdr = atable.rows[0].cells
    for i, name in enumerate((L["th_id"], L["th_severity"],
                              L["th_verification"], L["th_source"],
                              L["th_location"])):
        hdr[i].text = name
    for f in findings:
        row = atable.add_row().cells
        for i, val in enumerate((f["id"], f["severity"],
                                 f["verification"] or "—",
                                 f["source"] or "—",
                                 f["location"] or "—")):
            row[i].text = val

    # --- appendix B ---
    _docx_page_break(doc)
    doc.add_heading(L["appendix_b"], level=1)
    ran = (meta or {}).get("ran") or _collect_sources(findings)
    skipped = (meta or {}).get("skipped") or []
    doc.add_paragraph(L["ran_fmt"].format(
        x=("; ".join(str(x) for x in ran) if ran
           else L["none_recorded"])))
    doc.add_paragraph(L["skipped_fmt"].format(
        x=("; ".join(str(x) for x in skipped) if skipped
           else L["none"])))

    # --- footer ---
    doc.add_paragraph(L["end_of_report"])
    doc.add_paragraph(f"{L['disclaimer_label']} {L['disclaimer']}")

    import io
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


