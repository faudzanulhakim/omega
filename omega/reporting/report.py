def _cover_lines(target, generated_at, L=None):
    L = L or _EN
    return [
        L["title"],
        f"{L['target']}: {target or '(unspecified)'}",
        f"{L['engagement_date']}: {generated_at}",
        f"{L['version']}: {REPORT_VERSION}",
        L["classification"],
    ]


def _scope_lines(target, meta, findings=None, L=None):
    L = L or _EN
    m = meta or {}
    sources = _collect_sources(findings or [])
    tools = ("; ".join(sorted(set(sources)
                              | set(str(x) for x in (m.get("engines") or []))))
             or "OMEGA built-in engines")
    lines = [
        L["target_url"].format(target=target or "(unspecified)"),
        L["scope_statement"],
        L["methodology"],
        L["tools_used"].format(tools=tools),
    ]
    if m.get("skipped"):
        text = "; ".join(str(s) for s in m["skipped"])
    else:
        text = L["limitations_manual"]
    lines.append(L["limitations_fmt"].format(text=text))
    return lines


def _collect_sources(findings):
    srcs = set()
    for f in findings:
        s = f.get("source") or ""
        if s:
            srcs.add(s)
            head = s.split("/")[0].split(",")[0].strip()
            if head:
                srcs.add(head)
    return sorted(srcs)


def _risk_methodology_lines(L=None):
    L = L or _EN
    defs = dict(_SEVERITY_DEFS)
    lines = [L["severity_definitions"]]
    for sev in ("HIGH", "MEDIUM", "LOW", "INFO"):
        lines.append(L["sev_line_fmt"].format(sev=sev, text=defs[sev]))
    lines.append(L["verif_semantics"])
    return lines


def _footer_lines(L=None):
    L = L or _EN
    return [
        L["end_of_report"],
        f"{L['disclaimer_label']} {L['disclaimer']}",
    ]


