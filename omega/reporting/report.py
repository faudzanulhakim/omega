def _lang_key(lang=None):
    """Normalize a lang argument to a supported code ('en' fallback)."""
    if not lang:
        return "en"
    key = str(lang).strip().lower()
    key = {"zh-cn": "zh", "zh-hans": "zh", "pt-br": "pt",
           "in": "id", "iw": "iw"}.get(key, key.split("-")[0].split("_")[0])
    return key if key in LANGS else "en"


def resolve_lang(lang=None):
    """Return the label set for `lang`; unknown/missing values fall
    back to the 'en' label set. Never raises."""
    return LANGS[_lang_key(lang)]

