def _render_pdf(target, findings, summary, generated_at, meta=None,
                L=None):
    """Render a PDF via reportlab platypus. ImportError -> ReportError."""
    L = L or _EN
    try:
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
        from reportlab.lib.units import mm
        from reportlab.platypus import (PageBreak, Paragraph,
                                        SimpleDocTemplate, Spacer, Table,
                                        TableStyle)
    except ImportError as exc:
        raise ReportError(
            "pdf export requires reportlab "
            f"(pip install reportlab): {exc}") from exc
    import io
    s = summary
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4,
                            leftMargin=15 * mm, rightMargin=15 * mm,
                            topMargin=15 * mm, bottomMargin=15 * mm)
    styles = getSampleStyleSheet()
    mono = ParagraphStyle("Evidence", parent=styles["Code"],
                          fontName="Courier", fontSize=8, backColor="#F2F2F2")
    small = ParagraphStyle("Small", parent=styles["Normal"], fontSize=9)
    esc = (lambda t: str(t)
           .replace("&", "&amp;").replace("<", "&lt;")
           .replace(">", "&gt;"))

    story = []
    # --- cover ---
    story.append(Paragraph(esc(L["classification"]), styles["Heading2"]))
    story.append(Spacer(1, 18))
    story.append(Paragraph(esc(L["title"]), styles["Title"]))
    story.append(Spacer(1, 10))
    story.append(Paragraph(f"{esc(L['target'])}: {esc(target)}",
                           styles["Normal"]))
    story.append(Paragraph(f"{esc(L['engagement_date'])}: {generated_at}",
                           styles["Normal"]))
    story.append(Paragraph(f"{esc(L['version'])}: {REPORT_VERSION}",
                           styles["Normal"]))
    story.append(PageBreak())

    # --- findings index (TOC-like) ---
    story.append(Paragraph(esc(L["findings_index"]), styles["Heading2"]))
    for f in findings:
        story.append(Paragraph(
            f"{f['id']} [{f['severity']}] — {esc(f['title'])}", small))
    if not findings:
        story.append(Paragraph(esc(L["no_findings_pdf"]), small))
    story.append(PageBreak())

    # --- executive summary ---
    story.append(Paragraph(esc(L["executive_summary"]), styles["Heading2"]))
    story.append(Paragraph(_overall_risk_text(s, L), styles["Normal"]))
    story.append(Paragraph(
        L["severity_counts_fmt"].format(
            high=s['by_severity']['HIGH'],
            medium=s['by_severity']['MEDIUM'],
            low=s['by_severity']['LOW'],
            info=s['by_severity']['INFO'],
            confirmed=s['by_verification']['confirmed'],
            candidate=s['by_verification']['candidate'],
            corroborated=s['corroborated']), styles["Normal"]))
    for o in _key_observations(findings, s, L=L):
        story.append(Paragraph(f"• {esc(o)}", small))
    story.append(Spacer(1, 8))

    # --- scope & methodology ---
    story.append(Paragraph(esc(L["scope_methodology"]), styles["Heading2"]))
    for ln in _scope_lines(target, meta, findings, L=L):
        story.append(Paragraph(f"• {esc(ln)}", small))
    story.append(Spacer(1, 8))

    # --- risk rating methodology ---
    story.append(Paragraph(esc(L["risk_methodology"]), styles["Heading2"]))
    table = Table([[L["th_severity"], L["th_definition"]]] +
                  [[sev, defn] for sev, defn in _SEVERITY_DEFS],
                  colWidths=[60, 440])
    table.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.5, "#999999"),
        ("BACKGROUND", (0, 0), (-1, 0), "#DDDDDD"),
    ]))
    story.append(table)
    story.append(PageBreak())

    # --- findings ---
    story.append(Paragraph(esc(L["findings"]), styles["Heading2"]))
    for f in findings:
        story.append(Paragraph(
            f"{f['id']} [{f['severity']}] {esc(f['title'])}",
            styles["Heading3"]))
        status = _verification_status(f, L)
        if status:
            story.append(Paragraph(
                f"<b>{esc(L['verification_status'])}:</b> {esc(status)}",
                styles["Normal"]))
        if f.get("corroborated"):
            story.append(Paragraph(esc(_corroborated_note(f, L)),
                                   styles["Normal"]))
        if f.get("cwe") or f.get("cvss"):
            bits = []
            if f.get("cwe"):
                bits.append(f"CWE: {esc(f['cwe'])}")
            if f.get("cvss"):
                bits.append(f"CVSS: {esc(f['cvss'])}")
            story.append(Paragraph(" | ".join(bits), small))
        story.append(Paragraph(
            f"<b>{esc(L['description'])}:</b> {esc(f['description'])}",
            small))
        story.append(Paragraph(
            f"<b>{esc(L['impact'])}:</b> {esc(f['impact'])}", small))
        story.append(Paragraph(f"<b>{esc(L['evidence'])}:</b>", small))
        ev = f["evidence"] if f["evidence"] else L["no_evidence"]
        story.append(Paragraph(esc(ev), mono))
        story.append(Paragraph(
            f"<b>{esc(L['affected_location'])}:</b> "
            f"{esc(f['location'] or '—')}", small))
        if f["manual_check"]:
            story.append(Paragraph(
                f"<b>{esc(L['manual_verification_steps'])}:</b>", small))
            story.append(Paragraph(esc(f["manual_check"]), mono))
        story.append(Paragraph(
            f"<b>{esc(L['recommendation'])}:</b> "
            f"{esc(f['recommendation'])}", small))
        if f.get("references"):
            story.append(Paragraph(
                f"<b>{esc(L['references'])}:</b> " +
                "; ".join(esc(r) for r in f["references"]), small))
        story.append(Spacer(1, 8))
    story.append(PageBreak())

    # --- appendix A ---
    story.append(Paragraph(esc(L["appendix_a"]), styles["Heading2"]))
    atable = Table(
        [[L["th_id"], L["th_severity"], L["th_verification"],
          L["th_source"], L["th_location"]]] +
        [[f["id"], f["severity"], f["verification"] or "—",
          f["source"] or "—", f["location"] or "—"] for f in findings],
        colWidths=[40, 50, 80, 150, 140])
    atable.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.5, "#999999"),
        ("BACKGROUND", (0, 0), (-1, 0), "#DDDDDD"),
        ("FONTSIZE", (0, 0), (-1, -1), 7),
    ]))
    story.append(atable)

    # --- appendix B ---
    story.append(Spacer(1, 10))
    story.append(Paragraph(esc(L["appendix_b"]), styles["Heading2"]))
    ran = (meta or {}).get("ran") or _collect_sources(findings)
    skipped = (meta or {}).get("skipped") or []
    story.append(Paragraph(
        L["ran_fmt"].format(
            x=("; ".join(esc(str(x)) for x in ran) if ran
               else L["none_recorded"])), small))
    story.append(Paragraph(
        L["skipped_fmt"].format(
            x=("; ".join(esc(str(x)) for x in skipped) if skipped
               else L["none"])), small))

    # --- footer ---
    story.append(Spacer(1, 10))
    story.append(Paragraph(esc(L["end_of_report"]), styles["Normal"]))
    story.append(Paragraph(
        f"{esc(L['disclaimer_label'])} {esc(L['disclaimer'])}", small))

    doc.build(story)
    return buf.getvalue()


