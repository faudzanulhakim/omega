def _norm_severity(value):
    key = str(value or "").strip().lower()
    return _SEV_ALIASES.get(key, "INFO")


def _norm_cwe(value):
    """Normalize a cwe field to 'CWE-79' style, or ''."""
    text = str(value or "").strip().upper()
    if not text:
        return ""
    if text.isdigit():
        return f"CWE-{text}"
    if text.startswith("CWE") and not text.startswith("CWE-"):
        return "CWE-" + text[3:].lstrip("- ")
    if not text.startswith("CWE") and text[0].isdigit():
        return "CWE-" + text
    return text


def _default_description(f):
    loc = f["location"] or "the assessed target"
    src = f["source"] or "the OMEGA engine"
    return (f"The scanner {src} flagged '{f['title']}' at {loc}. "
            f"The observation is backed by captured evidence reproduced "
            f"below and should be reviewed in the context of the "
            f"application's business logic.")


def _recommendation_for(cwe, severity):
    if cwe and cwe in CWE_REMEDIATION:
        return CWE_REMEDIATION[cwe]
    if cwe:
        return (f"Review and remediate per OWASP guidance for {cwe}: "
                "verify the control server-side, apply "
                "defense-in-depth, and retest after the fix.")
    return GENERIC_RECOMMENDATION


def _references_for(cwe):
    if not cwe:
        return []
    refs = [cwe]
    link = CWE_LINKS.get(cwe)
    if link:
        refs.append(link)
    return refs


def sanitize_findings(findings):
    """Return a clean list of enriched finding dicts. Never raises.

    - non-dict entries are dropped
    - missing fields are coerced ('' / 'INFO' severity default)
    - evidence is truncated to EVIDENCE_MAX chars
    - cwe normalized; description/impact/recommendation defaulted from
      the CWE map or severity; references derived from cwe
    - dedupe by (title, location, source), keeping the highest severity
    - sorted by severity (HIGH > MEDIUM > LOW > INFO), then title
    - IDs assigned sequentially F-001, F-002, ... in sorted order
    """
    by_key = {}
    for f in (findings or []):
        if not isinstance(f, dict):
            continue
        title = str(f.get("title") or f.get("name") or "")
        location = str(f.get("location") or f.get("url")
                       or f.get("host") or "")
        source = str(f.get("source") or "")
        sev = _norm_severity(f.get("severity"))
        evidence = str(f.get("evidence") or "")[:EVIDENCE_MAX]
        cwe = _norm_cwe(f.get("cwe"))
        clean = {
            "title": title,
            "severity": sev,
            "confidence": str(f.get("confidence") or ""),
            "verification": str(f.get("verification") or ""),
            "source": source,
            "evidence": evidence,
            "location": location,
            "manual_check": str(f.get("manual_check") or ""),
            "description": str(f.get("description") or ""),
            "impact": str(f.get("impact") or ""),
            "recommendation": str(f.get("recommendation") or ""),
            "cwe": cwe,
        }
        if f.get("cvss") not in (None, ""):
            clean["cvss"] = str(f.get("cvss"))
        if f.get("corroborated"):
            clean["corroborated"] = True
        if "verification_note" in f:
            clean["verification_note"] = str(f.get("verification_note") or "")
        key = (title, location, source)
        prev = by_key.get(key)
        if prev is None or _SEV_ORDER[sev] < _SEV_ORDER[prev["severity"]]:
            by_key[key] = clean

    out = list(by_key.values())
    out.sort(key=lambda f: (_SEV_ORDER[f["severity"]], f["title"]))
    for i, f in enumerate(out, start=1):
        f["id"] = f"F-{i:03d}"
        if not f["description"]:
            f["description"] = _default_description(f)
        if not f["impact"]:
            f["impact"] = _IMPACT_DEFAULTS[f["severity"]]
        if not f["recommendation"]:
            f["recommendation"] = _recommendation_for(f["cwe"],
                                                      f["severity"])
        if not f.get("references"):
            f["references"] = _references_for(f["cwe"])
    return out


def report_summary(findings):
    """Summary counts dict used inside every format. Never raises."""
    findings = sanitize_findings(findings)
    by_severity = {sev: 0 for sev in SEVERITIES}
    by_verification = {"confirmed": 0, "candidate": 0, "other": 0}
    corroborated = 0
    for f in findings:
        by_severity[f["severity"]] += 1
        ver = f["verification"].strip().lower()
        if ver in ("confirmed", "candidate"):
            by_verification[ver] += 1
        else:
            by_verification["other"] += 1
        if f.get("corroborated"):
            corroborated += 1
    total = len(findings)
    if total == 0:
        risk_rating = "INFO"
    else:
        risk_rating = next(sev for sev in SEVERITIES
                           if by_severity[sev] > 0)
    return {
        "total": total,
        "by_severity": by_severity,
        "by_verification": by_verification,
        "corroborated": corroborated,
        "risk_rating": risk_rating,
    }


def _overall_risk_text(summary, L=None):
    L = L or _EN
    if summary["total"] == 0:
        return L["overall_risk_none"]
    rating = summary["risk_rating"]
    return L["overall_risk_fmt"].format(rating=rating,
                                        total=summary["total"])


def _key_observations(findings, summary, limit=5, L=None):
    """One-liner key observations for the executive summary."""
    L = L or _EN
    if summary["total"] == 0:
        return [L["no_findings_obs"]]
    obs = [f"{f['id']} ({f['severity']}): {f['title']}"
           for f in findings[:limit]]
    if summary["total"] > limit:
        obs.append(L["additional_findings_fmt"].format(
            n=summary["total"] - limit))
    return obs


def _verification_status(f, L=None):
    """Verification status string used in every human format."""
    L = L or _EN
    ver = f["verification"].strip().lower()
    if ver == "confirmed":
        return L["confirmed"]
    if ver == "candidate":
        return L["candidate_status"]
    if f.get("corroborated"):
        sources = [s for s in f["source"].split(",") if s.strip()]
        n = max(len(sources), 2)
        return L["corroborated_fmt"].format(n=n)
    return ""


def _corroboration_suffix(f, L=None):
    """Suffix noting corroboration for confirmed/candidate findings."""
    L = L or _EN
    if not f.get("corroborated"):
        return ""
    sources = [s for s in f["source"].split(",") if s.strip()]
    n = max(len(sources), 2)
    return L["corroboration_suffix_fmt"].format(n=n)


def _corroborated_note(f, L=None):
    L = L or _EN
    if not f.get("corroborated"):
        return ""
    src = f["source"] or "multiple scanners"
    return L["corroborated_note_fmt"].format(src=src)


