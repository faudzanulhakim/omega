def _markdown_finding(f, L=None):
    L = L or _EN
    lines = [f"### {f['id']} [{f['severity']}] {f['title']}"]
    status = _verification_status(f, L)
    if status:
        status += _corroboration_suffix(f, L)
        if f["verification"].strip().lower() == "confirmed":
            lines.append(f"**{L['verification']}: ✅ {status}**")
        else:
            lines.append(f"**{L['verification']}: ⚠️ {status}**")
    if f.get("corroborated"):
        lines.append(_corroborated_note(f, L))
    if f.get("cwe") or f.get("cvss"):
        bits = []
        if f.get("cwe"):
            bits.append(f"CWE: {f['cwe']}")
        if f.get("cvss"):
            bits.append(f"CVSS: {f['cvss']}")
        lines.append("*" + " | ".join(bits) + "*")
    lines.append("")
    lines.append(f"**{L['description']}:** {f['description']}")
    lines.append("")
    lines.append(f"**{L['impact']}:** {f['impact']}")
    lines.append("")
    lines.append(f"**{L['evidence']}:**")
    lines.append("```")
    lines.append(f["evidence"] if f["evidence"] else L["no_evidence"])
    lines.append("```")
    lines.append("")
    lines.append(f"**{L['affected_location']}:** {f['location'] or '—'}")
    if f["manual_check"]:
        lines.append("")
        lines.append(f"**{L['manual_verification_steps']}:**")
        lines.append("```bash")
        lines.append(f["manual_check"])
        lines.append("```")
    lines.append("")
    lines.append(f"**{L['recommendation']}:** {f['recommendation']}")
    if f.get("references"):
        lines.append("")
        lines.append(f"**{L['references']}:** " +
                     "; ".join(f["references"]))
    lines.append("")
    return "\n".join(lines)


def _generated_at():
    now = datetime.datetime.now(datetime.timezone.utc)
    return now.isoformat(timespec="seconds").replace("+00:00", "Z")


def _render_markdown(target, findings, summary, generated_at, meta=None,
                     L=None):
    L = L or _EN
    s = summary
    obs = _key_observations(findings, s, L=L)
    lines = [f"# {L['title']}",
             "",
             f"**{L['target']}:** {target}",
             f"**{L['engagement_date']}:** {generated_at}",
             f"**{L['version']}:** {REPORT_VERSION}",
             "",
             f"> **{L['classification']}**",
             "",
             f"## {L['executive_summary']}",
             "",
             _overall_risk_text(s, L),
             "",
             (L["severity_counts_fmt"].format(
                 high=s['by_severity']['HIGH'],
                 medium=s['by_severity']['MEDIUM'],
                 low=s['by_severity']['LOW'],
                 info=s['by_severity']['INFO'],
                 confirmed=s['by_verification']['confirmed'],
                 candidate=s['by_verification']['candidate'],
                 corroborated=s['corroborated'])),
             ""]
    if s["total"] == 0:
        lines.append(f"**{L['no_findings_exec']}**")
        lines.append("")
    lines.append(f"**{L['key_observations']}:**")
    for o in obs:
        lines.append(f"- {o}")
    lines += ["",
              f"## {L['scope_methodology']}",
              ""]
    lines += _scope_lines(target, meta, findings, L=L)
    lines += ["",
              f"## {L['risk_methodology']}",
              ""]
    lines += _risk_methodology_lines(L)
    lines += ["",
              f"## {L['findings']}",
              ""]
    for f in findings:
        lines.append(_markdown_finding(f, L))
    lines += [f"## {L['appendix_a']}",
              "",
              f"| {L['th_id']} | {L['th_severity']} | {L['th_verification']} "
              f"| {L['th_source']} | {L['th_location']} |",
              "|---|---|---|---|---|"]
    for f in findings:
        lines.append(f"| {f['id']} | {f['severity']} | "
                     f"{f['verification'] or '—'} | "
                     f"{f['source'] or '—'} | {f['location'] or '—'} |")
    lines += ["",
              f"## {L['appendix_b']}",
              ""]
    ran = (meta or {}).get("ran") or _collect_sources(findings)
    skipped = (meta or {}).get("skipped") or []
    lines.append(L["ran_fmt"].format(
        x=("; ".join(str(x) for x in ran) if ran
           else L["none_recorded"])))
    lines.append(L["skipped_fmt"].format(
        x=("; ".join(str(x) for x in skipped) if skipped
           else L["none"])))
    lines += ["",
              "---",
              ""]
    lines += _footer_lines(L)
    return "\n".join(lines)


