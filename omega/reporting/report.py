"""omega/report.py — the auto-report engine (professional deliverable).

Turns a list of findings (omega/fusion.py shape: title / severity /
confidence / verification / source / evidence / location / manual_check /
corroborated flags) into a consulting-grade penetration test report in
five formats: markdown, HTML (self-contained, no JS/external assets),
JSON (machine shape + report_meta), DOCX (python-docx) and PDF
(reportlab platypus).

Report structure (all human formats):
  1. Cover / header (title, target, engagement date, version, classification)
  2. Executive summary (overall risk rating, counts, key observations)
  3. Scope & methodology
  4. Risk rating methodology
  5. Findings (F-001..., severity desc then title, full per-finding sections)
  6. Appendix A — full technical evidence table
  7. Appendix B — scanner coverage
  8. Footer (end-of-report + disclaimer)

Design rules:
- sanitize_findings() never raises: garbage entries are dropped, missing
  fields are coerced, evidence truncated to EVIDENCE_MAX chars, IDs
  assigned (F-001...), defaults for description/impact/recommendation
  derived from the CWE map or severity.
- generate_session_report() is contained: any load/layout problem becomes
  a ReportError with a clear message.
- write_report() infers the format from the file extension and lets
  OSError propagate.
- No subprocesses; docx/pdf use their pure-Python libraries, everything
  else is pure Python string building.
"""

