_EXT_FMT = {".md": "markdown", ".markdown": "markdown",
            ".html": "html", ".htm": "html", ".json": "json",
            ".docx": "docx", ".pdf": "pdf"}

_BINARY_FMTS = ("docx", "pdf")


def generate_session_report(session_dir, fmt="markdown"):
    """Load a stored omega session (a directory containing session JSON
    per omega/session.py layout) and render a report from its findings.

    Raises ReportError (never the raw underlying error) when the
    directory or its layout does not match.
    """
    if fmt not in _FORMATS:
        raise ValueError(f"unknown report format: {fmt!r} "
                         f"(expected one of {', '.join(_FORMATS)})")
    if not os.path.isdir(session_dir):
        raise ReportError(f"session directory not found: {session_dir!r}")

    target = None
    findings = []
    state = None
    candidates = [os.path.join(session_dir, "session.json")]
    for fn in sorted(os.listdir(session_dir)):
        if fn.endswith(".json") and os.path.join(session_dir,
                                                 fn) not in candidates:
            candidates.append(os.path.join(session_dir, fn))
    last_err = "no session JSON document found"
    for path in candidates:
        try:
            with open(path, encoding="utf-8") as fh:
                doc = json.load(fh)
        except (OSError, ValueError) as exc:
            last_err = f"unreadable session file {path!r}: {exc}"
            continue
        if not isinstance(doc, dict):
            last_err = f"session file {path!r} is not a JSON object"
            continue
        state = doc.get("state") if isinstance(doc.get("state"), dict) \
            else doc
        if not isinstance(state, dict) or "findings" not in state:
            last_err = (f"session file {path!r} lacks the expected "
                        f"state/findings layout (omega/session.py)")
            continue
        target = doc.get("target") or state.get("target")
        raw = state.get("findings") or []
        if not isinstance(raw, list):
            last_err = (f"session file {path!r}: 'findings' is not a "
                        f"list")
            continue
        findings = raw
        break
    else:
        raise ReportError(
            f"cannot load session from {session_dir!r}: {last_err}")

    meta = {"session_dir": session_dir}
    return generate_report(target or "", findings, meta=meta, fmt=fmt)


def write_report(target, findings, path, fmt=None, meta=None, lang=None):
    """Sanitize findings, render and write the report file.

    Format inferred from the extension when fmt is None
    (.md => markdown, .html/.htm => html, .json => json,
    .docx => docx, .pdf => pdf; unknown extension => ValueError).
    docx/pdf formats write binary bytes; the others write UTF-8 text.
    Parent directories are created. OSError from the write propagates
    to the caller. Returns the path written. `lang` selects the label
    language (unknown/None -> English).
    """
    if fmt is None:
        ext = os.path.splitext(str(path))[1].lower()
        fmt = _EXT_FMT.get(ext)
        if fmt is None:
            raise ValueError(f"cannot infer report format from "
                             f"extension {ext!r} (path: {path!r})")
    content = generate_report(target, findings, meta=meta, fmt=fmt,
                              lang=lang)
    directory = os.path.dirname(os.path.abspath(str(path)))
    os.makedirs(directory, exist_ok=True)
    mode = "wb" if fmt in _BINARY_FMTS else "w"
    kwargs = {} if fmt in _BINARY_FMTS else {"encoding": "utf-8"}
    with open(path, mode, **kwargs) as fh:
        fh.write(content)
    return str(path)
