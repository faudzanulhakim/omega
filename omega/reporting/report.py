def generate_report(target, findings, meta=None, fmt="markdown",
                    lang=None):
    """Render a report.

    Returns a str for fmt in {'markdown', 'html', 'json'} and BINARY
    bytes for fmt in {'docx', 'pdf'}. Unknown fmt -> ValueError;
    missing optional dependency for docx/pdf -> ReportError.
    `lang` selects the label language (unknown/None -> English);
    finding content is never translated.
    """
    if fmt not in _FORMATS:
        raise ValueError(f"unknown report format: {fmt!r} "
                         f"(expected one of {', '.join(_FORMATS)})")
    L = resolve_lang(lang)
    lang_code = _lang_key(lang)
    findings = sanitize_findings(findings)
    summary = report_summary(findings)
    generated_at = _generated_at()
    if fmt == "markdown":
        return _render_markdown(target, findings, summary, generated_at,
                                meta=meta, L=L)
    if fmt == "html":
        return _render_html(target, findings, summary, generated_at,
                            meta=meta, lang_code=lang_code, L=L)
    if fmt == "json":
        return _render_json(target, findings, summary, generated_at,
                            meta=meta, lang_code=lang_code, L=L)
    if fmt == "docx":
        return _render_docx(target, findings, summary, generated_at,
                            meta=meta, L=L)
    return _render_pdf(target, findings, summary, generated_at,
                       meta=meta, L=L)


